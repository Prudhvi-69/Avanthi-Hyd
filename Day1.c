#include<stdio.h>
void main()
{
	int input1, input2, input3;
	scanf("%d%d%d",&input1,&input2,&input3);
	int sum = input1 + input2 + input3;		//adding values
	printf("\n Sum : %d",sum);
	int product = input1 * input2 * input3; // multipying those values
	printf("\n Product : %d ",product);
	int average = sum / 3;			// fnding the average
	printf("\n Average : %d ", average);
	printf("\n Percentage : %d% ", average); //display as percentage
}










